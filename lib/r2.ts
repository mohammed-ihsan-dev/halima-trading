/**
 * Cloudflare R2 product-image storage (server-only — never import from client components).
 *
 * Flow: an admin asks for a short-lived presigned PUT URL → the browser uploads directly to
 * R2 → the server verifies the stored object (size, content type, file signature) and only
 * then returns its public URL, which is saved in the product's existing `images: string[]`.
 *
 * Credentials are read from server environment variables and never leave the server.
 */
import { randomUUID } from "node:crypto";
import { DeleteObjectCommand, GetObjectCommand, HeadObjectCommand, PutObjectCommand, S3Client } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

export const R2_ENV_VARS = ["R2_ACCOUNT_ID", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY", "R2_BUCKET", "R2_PUBLIC_BASE_URL"] as const;

export const IMAGE_UPLOAD = {
  maxBytes: 5 * 1024 * 1024,
  maxFilesPerRequest: 10,
  presignExpirySeconds: 300,
  // Keys are unique per upload and never overwritten, so they can be cached forever.
  cacheControl: "public, max-age=31536000, immutable",
} as const;

export const ALLOWED_IMAGE_TYPES = { "image/jpeg": "jpg", "image/png": "png", "image/webp": "webp" } as const;
export type AllowedImageType = keyof typeof ALLOWED_IMAGE_TYPES;
const EXT_TO_TYPE: Record<string, AllowedImageType> = { jpg: "image/jpeg", png: "image/png", webp: "image/webp" };

export const IMAGE_KEY_PATTERN =
  /^products\/\d{4}\/(0[1-9]|1[0-2])\/[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}\.(jpg|png|webp)$/;

/* -------------------------------------------------------------------------- */
/* Configuration                                                              */
/* -------------------------------------------------------------------------- */

export interface R2Config {
  accountId: string;
  accessKeyId: string;
  secretAccessKey: string;
  bucket: string;
  publicBaseUrl: string; // https://…, no trailing slash
}

export type R2ConfigResult =
  | { ok: true; config: R2Config }
  | { ok: false; missing: string[]; invalid: string[] };

/** Reports missing or malformed variable NAMES only — values are never echoed. */
export function getR2Config(env: Record<string, string | undefined> = process.env): R2ConfigResult {
  const value = (name: string) => (env[name] ?? "").trim();
  const missing = R2_ENV_VARS.filter((name) => !value(name));
  const invalid: string[] = [];
  if (value("R2_ACCOUNT_ID") && !/^[0-9a-f]{32}$/i.test(value("R2_ACCOUNT_ID"))) invalid.push("R2_ACCOUNT_ID");
  if (value("R2_BUCKET") && !/^[a-z0-9][a-z0-9-]{1,61}[a-z0-9]$/.test(value("R2_BUCKET"))) invalid.push("R2_BUCKET");
  let publicBaseUrl = value("R2_PUBLIC_BASE_URL").replace(/\/+$/, "");
  if (publicBaseUrl) {
    try {
      const url = new URL(publicBaseUrl);
      if (url.protocol !== "https:" || url.search || url.hash) invalid.push("R2_PUBLIC_BASE_URL");
      publicBaseUrl = `${url.origin}${url.pathname.replace(/\/+$/, "")}`;
    } catch {
      invalid.push("R2_PUBLIC_BASE_URL");
    }
  }
  if (missing.length || invalid.length) return { ok: false, missing, invalid };
  return {
    ok: true,
    config: {
      accountId: value("R2_ACCOUNT_ID").toLowerCase(),
      accessKeyId: value("R2_ACCESS_KEY_ID"),
      secretAccessKey: value("R2_SECRET_ACCESS_KEY"),
      bucket: value("R2_BUCKET"),
      publicBaseUrl,
    },
  };
}

export const isR2UploadConfigured = (env: Record<string, string | undefined> = process.env) => getR2Config(env).ok;

