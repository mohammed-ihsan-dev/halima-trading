/* Keys, URLs and validation (pure)                                           */
/* -------------------------------------------------------------------------- */

/** Object keys are generated by the server only — never derived from the uploaded file name. */
export function createImageKey(contentType: AllowedImageType, now: Date = new Date(), uuid: string = randomUUID()): string {
  const month = String(now.getUTCMonth() + 1).padStart(2, "0");
  return `products/${now.getUTCFullYear()}/${month}/${uuid}.${ALLOWED_IMAGE_TYPES[contentType]}`;
}

export const isValidImageKey = (key: unknown): key is string => typeof key === "string" && IMAGE_KEY_PATTERN.test(key);
export const contentTypeForKey = (key: string): AllowedImageType => EXT_TO_TYPE[key.slice(key.lastIndexOf(".") + 1)];

export const publicUrlForKey = (publicBaseUrl: string, key: string) => `${publicBaseUrl}/${key}`;

/** The key of an image URL served from this bucket's public domain, or null. */
export function keyFromPublicUrl(publicBaseUrl: string, url: string): string | null {
  const prefix = `${publicBaseUrl}/`;
  if (!url.startsWith(prefix)) return null;
  const key = url.slice(prefix.length);
  return isValidImageKey(key) ? key : null;
}

export function validateUploadRequest(file: { contentType?: unknown; size?: unknown }): string | null {
  if (typeof file.contentType !== "string" || !(file.contentType in ALLOWED_IMAGE_TYPES)) {
    return "Only JPEG, PNG and WebP images can be uploaded.";
  }
  if (typeof file.size !== "number" || !Number.isInteger(file.size) || file.size <= 0) return "File size is missing or invalid.";
  if (file.size > IMAGE_UPLOAD.maxBytes) return `Images must be ${IMAGE_UPLOAD.maxBytes / 1024 / 1024} MB or smaller.`;
  return null;
}

/** Identifies JPEG, PNG or WebP from the first bytes of the file, regardless of its claimed type. */
export function detectImageType(bytes: Uint8Array): AllowedImageType | null {
  const b = bytes;
  if (b.length >= 3 && b[0] === 0xff && b[1] === 0xd8 && b[2] === 0xff) return "image/jpeg";
  if (b.length >= 8 && [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a].every((v, i) => b[i] === v)) return "image/png";
  const ascii = (from: number, to: number) => String.fromCharCode(...b.slice(from, to));
  if (b.length >= 12 && ascii(0, 4) === "RIFF" && ascii(8, 12) === "WEBP") return "image/webp";
  return null;
}

