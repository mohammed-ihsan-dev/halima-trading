/* Storage operations                                                         */
/* -------------------------------------------------------------------------- */

/** The only storage operations the app uses — an interface so verification is testable offline. */
export interface ImageObjectStore {
  presignPut(key: string, contentType: AllowedImageType, size: number): Promise<string>;
  head(key: string): Promise<{ size: number; contentType: string } | null>;
  readPrefix(key: string, bytes: number): Promise<Uint8Array>;
  delete(key: string): Promise<void>;
}

export function createR2Client(config: R2Config): S3Client {
  return new S3Client({
    region: "auto", // required by the SDK, not used by R2
    endpoint: `https://${config.accountId}.r2.cloudflarestorage.com`,
    credentials: { accessKeyId: config.accessKeyId, secretAccessKey: config.secretAccessKey },
    // https://<account>.r2.cloudflarestorage.com/<bucket>/<key> — one predictable upload host.
    forcePathStyle: true,
    // Only add checksums when an operation requires them, so presigned upload URLs carry no
    // checksum parameter the browser would have to satisfy.
    requestChecksumCalculation: "WHEN_REQUIRED",
    responseChecksumValidation: "WHEN_REQUIRED",
  });
}

export function createR2Store(config: R2Config, client: S3Client = createR2Client(config)): ImageObjectStore {
  const Bucket = config.bucket;
  return {
    presignPut(key, contentType, size) {
      // Content-Type, Content-Length and Cache-Control are signed: the upload must match them exactly.
      return getSignedUrl(
        client,
        new PutObjectCommand({ Bucket, Key: key, ContentType: contentType, ContentLength: size, CacheControl: IMAGE_UPLOAD.cacheControl }),
        { expiresIn: IMAGE_UPLOAD.presignExpirySeconds, signableHeaders: new Set(["content-type", "content-length", "cache-control"]) }
      );
    },
    async head(key) {
      try {
        const res = await client.send(new HeadObjectCommand({ Bucket, Key: key }));
        return { size: Number(res.ContentLength ?? 0), contentType: res.ContentType ?? "" };
      } catch (error) {
        const status = (error as { $metadata?: { httpStatusCode?: number } }).$metadata?.httpStatusCode;
        if (status === 404 || (error as Error).name === "NotFound") return null;
        throw error;
      }
    },
    async readPrefix(key, bytes) {
      const res = await client.send(new GetObjectCommand({ Bucket, Key: key, Range: `bytes=0-${bytes - 1}` }));
      return res.Body ? await res.Body.transformToByteArray() : new Uint8Array();
    },
    async delete(key) {
      await client.send(new DeleteObjectCommand({ Bucket, Key: key }));
    },
  };
}

export type VerifyResult = { ok: true; contentType: AllowedImageType; size: number } | { ok: false; reason: string };

/**
 * Confirms an uploaded object is what was approved: present, within the size limit, stored with
 * the expected content type and actually that image format. Anything else is deleted.
 */
export async function verifyUploadedImage(store: ImageObjectStore, key: string): Promise<VerifyResult> {
  if (!isValidImageKey(key)) return { ok: false, reason: "Invalid upload key." };
  const expected = contentTypeForKey(key);
  const head = await store.head(key);
  if (!head) return { ok: false, reason: "The upload was not found — it may not have finished or the link expired." };

  const reject = async (reason: string): Promise<VerifyResult> => {
    await store.delete(key);
    return { ok: false, reason };
  };
  if (head.size <= 0 || head.size > IMAGE_UPLOAD.maxBytes) return reject("The uploaded file is empty or too large.");
  if (head.contentType.split(";")[0].trim().toLowerCase() !== expected) return reject("The uploaded file's type does not match.");
  const actual = detectImageType(await store.readPrefix(key, 16));
  if (actual !== expected) return reject("The uploaded file is not a valid image.");
  return { ok: true, contentType: expected, size: head.size };
}
